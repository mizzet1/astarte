#!/usr/bin/env bash
# Prepare a local Astarte (docker compose) for `cargo e2e`, mirroring the
# steps of the `end-to-end-next-test` CI job: realm keypair, realm, e2e
# interfaces, a registered device and a JWT. The resulting configuration is
# written to `.local/e2e.env`, to be sourced before running the tests.
#
# Safe to run more than once: the keypair and realm are reused, while the
# device and the JWT are regenerated on every run.

set -euo pipefail

e2e_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
repo_dir="$(cd "$e2e_dir/../.." && pwd)"

astarte_url="${E2E_ASTARTE_API_URL:-http://api.astarte.localhost}"
astarte_url="${astarte_url%/}"
realm="${E2E_REALM:-test}"
housekeeping_key="${HOUSEKEEPING_KEY:-$repo_dir/compose/astarte-keys/housekeeping_private.pem}"
state_dir="$e2e_dir/.local"
env_file="$state_dir/e2e.env"
realm_private_key="$state_dir/${realm}_private.pem"
realm_public_key="$state_dir/${realm}_public.pem"

info() { printf '==> %s\n' "$*" >&2; }
die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

command -v astartectl >/dev/null || die "astartectl not found in PATH"
command -v curl >/dev/null || die "curl not found in PATH"
[[ -f $housekeeping_key ]] || die "housekeeping key not found at $housekeeping_key, run the docker-compose-initializer first"

mkdir -p "$state_dir"

# Keep astartectl from creating contexts in the user's configuration, and drop
# the warning it prints when that configuration is empty.
actl() {
    astartectl --config-dir "$state_dir/astartectl" "$@" \
        2> >(grep -v '^warn: Error while loading configuration' >&2)
}

info "waiting for the Astarte APIs at $astarte_url"
for attempt in $(seq 1 60); do
    healthy=0
    for api in housekeeping realmmanagement pairing appengine; do
        status="$(curl -s -o /dev/null -w '%{http_code}' --max-time 3 "$astarte_url/$api/health" || true)"
        [[ $status == 200 ]] && healthy=$((healthy + 1))
    done
    [[ $healthy == 4 ]] && break
    [[ $attempt == 60 ]] && die "Astarte APIs not healthy after 5 minutes, check \`docker compose ps\`"
    sleep 5
done

if [[ ! -f $realm_private_key ]]; then
    info "generating the keypair for realm $realm"
    (cd "$state_dir" && actl utils gen-keypair "$realm" >/dev/null)
fi

if actl housekeeping realms show "$realm" -u "$astarte_url" -k "$housekeeping_key" >/dev/null 2>&1; then
    info "realm $realm already exists"
else
    info "creating realm $realm"
    actl housekeeping realms create "$realm" -u "$astarte_url" -k "$housekeeping_key" \
        --realm-public-key "$realm_public_key" -y >/dev/null

    # The realm is not immediately usable by the other services.
    sleep 5
fi

if ! actl realm-management interfaces ls -u "$astarte_url" -r "$realm" -k "$realm_private_key" >/dev/null 2>&1; then
    die "realm $realm rejects the key in $state_dir; it was probably created with another key, use a different E2E_REALM"
fi

info "syncing the e2e interfaces"
actl realm-management interfaces sync -u "$astarte_url" -r "$realm" -k "$realm_private_key" -y \
    "$e2e_dir"/astarte-e2e/interfaces/*.json >/dev/null

info "registering a device"
device_id="$(actl utils device-id generate-random)"
credentials_secret="$(actl pairing agent register "$device_id" -u "$astarte_url" -r "$realm" \
    -k "$realm_private_key" --compact-output)"

info "generating the JWT"
jwt="$(actl utils gen-jwt appengine channels pairing realm-management -k "$realm_private_key")"

cat >"$env_file" <<EOF
# Generated by scripts/setup-local.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ), the JWT expires after 8 hours.
export E2E_ASTARTE_API_URL=$astarte_url/
export E2E_REALM=$realm
export E2E_JWT=$jwt
export E2E_DEVICE_ID=$device_id
export E2E_CREDENTIALS_SECRET=$credentials_secret
export E2E_AMQP_CONSUMER_HOST=127.0.0.1
export E2E_IGNORE_SSL_ERRORS=true
EOF

info "wrote $env_file"
info "run the tests with: source .local/e2e.env && cargo e2e"
